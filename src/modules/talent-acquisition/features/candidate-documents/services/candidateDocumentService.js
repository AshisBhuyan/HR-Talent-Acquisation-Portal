import { delay } from '../../../services/mockBackend.js';
import { getDocumentTypeLabel } from '../../../constants/candidateDocumentRules.js';
import { formatDate } from '../../../utils/formatDate.js';

/**
 * Candidate document service.
 *
 * Candidates upload their CV and certificates through the Career Portal. The
 * Talent Acquisition module only reads the document metadata that the backend
 * exposes. For the seeded demonstration records a small, printable sample
 * document is generated in the browser so the preview and download actions
 * are genuinely usable without storing any binary in local storage.
 */

const objectUrlCache = new Map();

function escapePdfText(value) {
  return String(value ?? '')
    .replace(/\\/g, '\\\\')
    .replace(/\(/g, '\\(')
    .replace(/\)/g, '\\)');
}

function buildSamplePdf(title, lines) {
  const content = [
    'BT',
    '/F1 16 Tf',
    '56 780 Td',
    `(${escapePdfText(title)}) Tj`,
    '/F1 10 Tf',
    ...lines.map((line) => `0 -18 Td (${escapePdfText(line)}) Tj`),
    'ET',
  ].join('\n');

  const objects = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>',
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
    `<< /Length ${content.length} >>\nstream\n${content}\nendstream`,
  ];

  let pdf = '%PDF-1.4\n';
  const offsets = [];

  objects.forEach((body, index) => {
    offsets.push(pdf.length);
    pdf += `${index + 1} 0 obj\n${body}\nendobj\n`;
  });

  const xrefOffset = pdf.length;
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  offsets.forEach((offset) => {
    pdf += `${String(offset).padStart(10, '0')} 00000 n \n`;
  });
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF`;

  return new Blob([pdf], { type: 'application/pdf' });
}

function buildDocumentLines(document, candidate, job) {
  const lines = [
    `Document: ${getDocumentTypeLabel(document.type)}`,
    `Candidate: ${candidate?.fullName || 'Unknown candidate'}`,
    `Candidate ID: ${candidate?.candidateId || '—'}`,
    `Position: ${job?.title || '—'}`,
    `Uploaded: ${formatDate(document.uploadedAt)}`,
    '',
    'This is a demonstration document generated by the Ecometrix Talent',
    'Acquisition module. The Career Portal stores the original file; the',
    'Talent Acquisition module renders and downloads the document metadata',
    'that the backend exposes.',
  ];

  if (Array.isArray(candidate?.skills) && candidate.skills.length) {
    lines.push('', `Skills: ${candidate.skills.join(', ')}`);
  }

  return lines;
}

function getCacheKey(document, candidate, job) {
  return [document?.documentId || document?.fileName || 'doc', candidate?.candidateId, job?.jobId].join(
    '::'
  );
}

export const candidateDocumentService = {
  async getDocuments(candidate) {
    await delay(120);
    const documents = Array.isArray(candidate?.documents) ? candidate.documents : [];
    return documents.map((document) => ({
      ...document,
      label: getDocumentTypeLabel(document.type),
      isAvailable: Boolean(document.fileName),
    }));
  },

  hasPreview(document) {
    return Boolean(document?.fileName);
  },

  /**
   * Returns an object URL for the inline preview. The URL lives for the
   * browser session only.
   */
  getPreviewUrl(document, { candidate, job } = {}) {
    if (!this.hasPreview(document)) return null;

    const key = getCacheKey(document, candidate, job);
    if (objectUrlCache.has(key)) return objectUrlCache.get(key);

    const blob = buildSamplePdf(
      document.fileName || 'Candidate document',
      buildDocumentLines(document, candidate, job)
    );
    const url = URL.createObjectURL(blob);
    objectUrlCache.set(key, url);
    return url;
  },

  downloadDocument(document, { candidate, job } = {}) {
    const url = this.getPreviewUrl(document, { candidate, job });
    if (!url) {
      throw new Error('This document is unavailable for download.');
    }

    const link = document.createElement('a');
    link.href = url;
    link.download = document.fileName || 'candidate-document.pdf';
    document.body.appendChild(link);
    link.click();
    link.remove();
  },

  releasePreview(document, { candidate, job } = {}) {
    const key = getCacheKey(document, candidate, job);
    const url = objectUrlCache.get(key);
    if (url) {
      URL.revokeObjectURL(url);
      objectUrlCache.delete(key);
    }
  },
};

export default candidateDocumentService;
